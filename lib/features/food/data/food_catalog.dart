/// Built-in list of common foods with a typical portion and APPROXIMATE
/// nutrition per portion. Values are typical home/restaurant recipes
/// rounded for quick logging, not lab measurements — coconut, oil and
/// portion size vary a lot, especially in Kerala and Indian cooking.
/// Bundled in the app (offline, no lookups).
library;

enum FoodCategory {
  kerala('Kerala'),
  southIndian('South Indian'),
  northIndian('North Indian'),
  eggs('Eggs'),
  rice('Rice & breads'),
  protein('Protein & gym'),
  snacks('Snacks & sweets'),
  fruit('Fruit'),
  drinks('Drinks'),
  fastFood('Fast food');

  const FoodCategory(this.label);
  final String label;
}

class CatalogFood {
  const CatalogFood(
    this.name,
    this.category,
    this.portion,
    this.kcal,
    this.protein,
    this.carbs,
    this.fat, {
    this.aliases = const [],
  });

  final String name;
  final FoodCategory category;

  /// Human description of one serving, e.g. "1 piece (~100 g)".
  final String portion;
  final int kcal;
  final double protein;
  final double carbs;
  final double fat;

  /// Other names people search for (Malayalam/Hindi names, spellings).
  final List<String> aliases;
}

/// Case-insensitive search across names, aliases and categories. Every
/// word must match; results keep catalogue order within each category.
List<CatalogFood> searchFoods(String query, {FoodCategory? category}) {
  final words = query
      .toLowerCase()
      .split(RegExp(r'\s+'))
      .where((w) => w.isNotEmpty)
      .toList();
  return [
    for (final f in foodCatalog)
      if (category == null || f.category == category)
        if (words.every(
          (w) =>
              f.name.toLowerCase().contains(w) ||
              f.category.label.toLowerCase().contains(w) ||
              f.aliases.any((a) => a.toLowerCase().contains(w)),
        ))
          f,
  ];
}

